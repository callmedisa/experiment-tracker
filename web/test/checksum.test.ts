import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { sha256Hex } from "../src/lib/sha256";
import { canonicalLine, checksum, doubleHex } from "../src/lib/checksum";

const fx = JSON.parse(readFileSync(new URL("./fixtures/checksum-vectors.json", import.meta.url), "utf8"));
const enc = (s: string) => new TextEncoder().encode(s);

describe("sha256", () => {
  it("matches known vectors", () => {
    expect(sha256Hex(enc(""))).toBe("e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855");
    expect(sha256Hex(enc("abc"))).toBe("ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
  });
  it("matches node's sha256 for many lengths (padding boundaries 55, 56, 63, 64, 65)", () => {
    for (const n of [1, 54, 55, 56, 57, 63, 64, 65, 119, 120, 128, 1000, 10007]) {
      const s = "x".repeat(n);
      expect(sha256Hex(enc(s))).toBe(createHash("sha256").update(s).digest("hex"));
    }
  });
});

describe("checksum parity with the Python server (fixture generated by backend/app/streaming.py)", () => {
  it("serialises every awkward double exactly like the server", () => {
    fx.rows.forEach((r: any, i: number) => expect(canonicalLine(r)).toBe(fx.lines[i]));
  });
  it("matches the server's checksum for the full set, a subset and the empty set", () => {
    expect(checksum(fx.rows)).toBe(fx.checksum);
    expect(checksum(fx.rows.slice(0, 3))).toBe(fx.first3);
    expect(checksum([])).toBe(fx.empty);
  });
  it("does not depend on input order", () => {
    expect(checksum([...fx.rows].reverse())).toBe(fx.checksum);
  });
  it("tells 0 from -0 and keeps tiny/huge doubles", () => {
    expect(doubleHex(0)).toBe("0000000000000000");
    expect(doubleHex(-0)).toBe("8000000000000000");
    expect(doubleHex(5e-324)).toBe("0000000000000001");
    expect(doubleHex(1)).toBe("3ff0000000000000");
  });
});
