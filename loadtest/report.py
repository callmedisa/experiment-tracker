#!/usr/bin/env python3
"""Turns the raw files of one load run into results.md (tables only: numbers, no verdict). usage: report.py results/load/<run>"""
import json
import sys
from pathlib import Path

d = Path(sys.argv[1])
s = json.loads((d / "summary.json").read_text())
per_run = json.loads((d / "per_run.json").read_text())
readers = json.loads((d / "readers.json").read_text())
ingest = json.loads((d / "ingest_samples.json").read_text())
res = json.loads((d / "resources.json").read_text())


def f(x, n=1):
    return "—" if x is None else (f"{x:.{n}f}" if isinstance(x, float) else str(x))


def lat(t):
    return f"| {t['n']} | {f(t['p50'])} | {f(t['p95'])} | {f(t['p99'])} | {f(t['max'])} |"


L = []
L.append(f"# Load run results: `{d.name}`\n")
L.append("Generated by loadtest/report.py from the raw files in this folder. Numbers only; no verdict.\n")
a = s["args"]
L.append(f"Workload: {a['runs']} runs x {a['rate']} events/s for {a['duration']} s, batches of 10-50 points, 1 normal reader per run (drops its connection "
         f"every 20-60 s and resumes from its cursor), {a['slow_readers']} slow readers (~2 events/s while ingesting), 2 pollers of `GET /runs` every 2 s. "
         f"Through nginx on one machine (Docker: see settings.txt). Producers finished after {s['producers_finished_after_s']} s; run ended after {s['total_s']} s.\n")
L.append("## Volume and throughput\n")
L.append(f"- events acknowledged by the API (intended): **{s['events_intended']:,}**; stored in Postgres for these runs: **{s['events_stored']:,}**")
L.append(f"- average throughput over the ingest window: **{s['throughput_events_per_s_over_ingest_window']} events/s** (target {a['runs'] * a['rate']})")
L.append(f"- ingest requests (all attempts): {s['ingest_requests']:,}; errors by kind: {s['ingest_errors'] or 'none'}; retries: {s['ingest_retries']}; batches given up: {s['ingest_gave_up']}\n")
L.append("## Latency (ms)\n")
L.append("| measure | n | p50 | p95 | p99 | max |\n|---|---|---|---|---|---|")
L.append("| ingest request (successful) " + lat(s["ingest_latency_ms_ok"]))
L.append("| ingest request (all attempts) " + lat(s["ingest_latency_ms_all_attempts"]))
L.append("| stream delay, normal readers (reader receipt - start of the POST that carried the event; includes ingest time) " + lat(s["stream_delay_ms_normal_readers"]))
L.append("| `GET /runs` (50 runs, growing) " + lat(s["runs_list_latency_ms"]) + "\n")
L.append(f"`GET /runs` non-200 responses: {s['runs_list_non200']}.\n")
L.append("Ingest p95 per minute of the run (ms), to see drift: " + ", ".join(f"min {k}: {f(v)}" for k, v in s["ingest_p95_per_minute_ms"].items()) + "\n")
L.append("## Lost and duplicate events (measured against Postgres and against what each reader received)\n")
L.append("| measure | count |\n|---|---|")
L.append(f"| acknowledged points missing from Postgres (lost on ingest) | {s['lost_on_ingest_total']} |")
L.append(f"| duplicate `point_id` rows in Postgres | {s['duplicates_in_db_total']} |")
L.append(f"| runs whose stored seqs are not exactly 1..N | {len(s['runs_not_contiguous'])} |")
L.append(f"| stored events a reader never received (summed over {len(readers)} readers, after draining to `closed`) | {s['lost_at_readers_total']} |")
L.append(f"| events a reader received more than once (summed) | {s['duplicate_deliveries_total']} |")
L.append(f"| readers that never saw `closed` before the drain limit | {s['readers_that_never_saw_closed']} |")
L.append(f"| reader reconnects (total) | {s['reader_reconnects_total']} |\n")
slow = [r for r in readers if r["slow"]]
L.append("Slow readers (read ~2 events/s while 10/s were produced, then drained):\n")
L.append("| reader | stored | received unique | lost | duplicate deliveries | saw closed |\n|---|---|---|---|---|---|")
for r in slow:
    L.append(f"| {r['reader']} (run {r['run'][-6:]}) | {r['stored']} | {r['received_unique']} | {r['lost']} | {r['duplicate_deliveries']} | {r['saw_closed']} |")
L.append("")
L.append("## Resources (docker stats, sampled about every 10 s)\n")
L.append("| container | samples | CPU % mean | CPU % max | memory MB first | max | last |\n|---|---|---|---|---|---|---|")
for n, r in sorted(s["resources"].items()):
    L.append(f"| {n} | {r['samples']} | {f(r['cpu_pct_mean'])} | {f(r['cpu_pct_max'])} | {f(r['mem_mb_first'])} | {f(r['mem_mb_max'])} | {f(r['mem_mb_last'])} |")
pg = s["pg_connections"]
L.append(f"\nPostgres connections to the `tracker` database: max {pg['max']}, mean {f(pg['mean'])}; max active at a sample: {pg['active_max']}.\n")
L.append("Container restarts / OOM kills after the run:\n```\n" + s["containers"] + "\n```\n")
bad = [r for r in per_run if r["lost_on_ingest"] or r["stored_not_intended"] or not r["contiguous"] or r["distinct"] != r["stored"]]
L.append(f"## Per-run reconciliation\n\n{len(per_run)} runs; rows with any discrepancy (lost on ingest, stored but not acknowledged, non-contiguous seq, duplicate ids): **{len(bad)}**.\n")
if bad:
    L.append("| run | intended | stored | distinct | contiguous | lost on ingest | stored not acknowledged |\n|---|---|---|---|---|---|---|")
    for r in bad:
        L.append(f"| {r['run']} | {r['intended']} | {r['stored']} | {r['distinct']} | {r['contiguous']} | {r['lost_on_ingest']} | {r['stored_not_intended']} |")
L.append("\nThe fastest and slowest runs by stored events: " + ", ".join(f"{r['stored']}" for r in sorted(per_run, key=lambda r: r['stored'])[:1] + sorted(per_run, key=lambda r: r['stored'])[-1:]) + ".\n")
L.append("## What was not measured here\n")
L.append("- the load generator ran on the same machine as the stack (it competes for CPU); Docker Desktop on one laptop; one API process; no network latency")
L.append("- stream delay is an upper bound that includes ingest time; the server's own `received_at` was not compared (host and container clocks)")
L.append("- browsers were not used: readers are HTTP clients, so rendering cost of the UI under this load is not in these numbers")
L.append("- no chaos proxy and no fault hooks in the path; failures other than the periodic client-side disconnects were not injected")
L.append("- the database already held earlier test data (see settings.txt); a fresh database was not used")
(d / "results.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
